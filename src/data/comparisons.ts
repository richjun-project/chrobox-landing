function localizeFeatureValue(value: boolean | string, lang: ContentLanguage): boolean | string {
  return typeof value === 'string' ? FEATURE_VALUE_LABELS[value]?.[lang] ?? value : value;
}

export function localizeComparisonData(
  comparison: ComparisonData,
  lang?: ContentLanguage,
): ComparisonData {
  if (!lang || lang === 'en') {
    return comparison;
  }

  // Korean is authored inline on the source record; resolving it here too lets
  // consumers read one shape for every locale instead of branching on `ko`.
  if (lang === 'ko') {
    return {
      ...comparison,
      competitor: comparison.competitorKo || comparison.competitor,
      tagline: comparison.taglineKo || comparison.tagline,
      description: comparison.descriptionKo || comparison.description,
      metaDescription: comparison.metaDescriptionKo || comparison.metaDescription,
      features: comparison.features.map((feature) => ({
        ...feature,
        name: feature.nameKo || feature.name,
        chrobox: localizeFeatureValue(feature.chrobox, lang),
        competitor: localizeFeatureValue(feature.competitor, lang),
      })),
      chroboxPros: comparison.chroboxProsKo?.length ? comparison.chroboxProsKo : comparison.chroboxPros,
      competitorPros: comparison.competitorProsKo?.length
        ? comparison.competitorProsKo
        : comparison.competitorPros,
      verdict: comparison.verdictKo || comparison.verdict,
      faqs: comparison.faqs.map((faq) => ({
        ...faq,
        question: faq.questionKo || faq.question,
        answer: faq.answerKo || faq.answer,
      })),
    };
  }

  const copy = LOCALIZED_CONTENT[lang]?.comparisons[comparison.slug];

  if (!copy) {
    return comparison;
  }

  return {
    ...comparison,
    competitor: copy.competitor ?? comparison.competitor,
    tagline: copy.tagline,
    description: copy.description,
    metaDescription: copy.metaDescription ?? copy.description,
    features: comparison.features.map((feature, index) => ({
      ...feature,
      name: copy.featureNames[index] ?? feature.name,
      chrobox: localizeFeatureValue(feature.chrobox, lang),
      competitor: localizeFeatureValue(feature.competitor, lang),
    })),
    chroboxPros: copy.chroboxPros,
    competitorPros: copy.competitorPros,
    verdict: copy.verdict,
    faqs: comparison.faqs.map((faq, index) => (copy.faqs[index]
      ? { ...faq, question: copy.faqs[index].question, answer: copy.faqs[index].answer }
      : faq)),
  };
}

export function getComparison(slug: string, lang?: ContentLanguage): ComparisonData | undefined {
  const comparison = comparisons.find((c) => c.slug === slug);
  return comparison ? localizeComparisonData(comparison, lang) : undefined;
}

export function getComparisons(lang?: ContentLanguage): ComparisonData[] {
  return comparisons.map((comparison) => localizeComparisonData(comparison, lang));
}
